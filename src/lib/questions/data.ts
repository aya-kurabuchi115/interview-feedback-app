// ヘルパー関数
export function getQuestionById(id: string): Question | undefined {
  return questions.find((q) => q.id === id);
}

export function filterQuestions(filters: {
  industry?: string;
  round?: string;
  type?: string;
  search?: string;
}): Question[] {
  return questions.filter((q) => {
    if (filters.industry && !q.industry.includes(filters.industry as Question["industry"][number])) {
      return false;
    }
    if (filters.round && !q.round.includes(filters.round as Question["round"][number])) {
      return false;
    }
    if (filters.type && q.type !== filters.type) {
      return false;
    }
    if (filters.search && !q.question.includes(filters.search)) {
      return false;
    }
    return true;
  });
}
